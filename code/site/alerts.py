"""alerts.py -- outcome alerts on indahl.ai (10 Nov 2026). Build hook for build_site.py, called once after the brand pages are built.

  apply(PAGES, page, hero_slim, HOME, bb, rows)
    - the desks that can send an alert: every live-headline desk (ledger/live_headlines.py DESKS) whose rule can write a value row after its
      baseline (a flip rule with no outcome never can) and whose page is built
    - the organisations that can: a brand page with rows on at least one of those desks
    - writes alerts_list.js (the worker's list of desks and organisations) and alerts_map.json (the same, read by alerts_send.py)
    - puts the sign-up box on each of those desk pages and brand pages, and builds /alerts (every desk, tick the ones you want)
The worker side is alerts.js. The sender is alerts_send.py, a tick-bus rider. Python 3.9+."""
import os, sys, json, html, hashlib
HERE = os.path.dirname(os.path.abspath(__file__)); B = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(B, 'ledger'))
E = html.escape
MAP = os.path.join(HERE, 'alerts_map.json'); LIST_JS = os.path.join(HERE, 'alerts_list.js')
JS_HASH_SRC = 'alerts.js v1'   # bump with a change to the script served at /alerts.js

CSS = """
.al{margin:18px 0 10px;max-width:620px;border-top:1px solid var(--rule);padding-top:12px}.al-h{font-weight:600;margin:0 0 6px}
.al input[type=email]{font:inherit;padding:6px 8px;border:1px solid var(--rule);background:var(--paper);min-width:0;width:min(320px,100%);margin:0 8px 6px 0}
.al .btn{vertical-align:top}.al-c{display:block;margin:2px 0 8px;font-size:15px}.al-say{font-size:14px;color:var(--mid);margin:4px 0 0}
.al-msg{margin:6px 0 0;font-weight:600}.al-msg:empty{display:none}.al-list{list-style:none;padding:0;margin:6px 0 12px}.al-list li{margin:6px 0;line-height:1.4}
"""


def alertable(PAGES):
    import live_headlines as LH
    out = {}
    for s, spec in LH.DESKS.items():
        if spec['kind'] == 'flip' and not spec.get('outcome'): continue
        if '/' + s not in PAGES: continue
        out[s] = [spec['name'], LH.H2.get(s, '')]
    return out


def brand_desks(bb, rows, desks):
    out = {}
    for slug, (e, items) in bb.items():
        ds = sorted({rows[i]['key'] for i, _ in items if rows[i]['key'] in desks})
        if ds: out[slug] = [e['name'], ds]
    return out


def _names(xs):
    xs = list(xs)
    return xs[0] if len(xs) == 1 else ', '.join(xs[:-1]) + ' and ' + xs[-1]


SAY = ('One email when the outcome changes, for example from consistent to above, or when a new value passes the desk&rsquo;s rule. '
       'We email a confirmation link first and send nothing else until you open it. Every alert has a link to manage or unsubscribe. ')


def _form(boxes, head):
    return ('<form class="al" action="/alerts/subscribe" method="post"><p class="al-h">%s</p>' % head
            + '<input type="email" name="email" required maxlength="160" autocomplete="email" placeholder="Email address" aria-label="Email address">'
            + '<input class="nl-hp" type="text" name="website" tabindex="-1" autocomplete="off" aria-hidden="true">'
            + '<button class="btn" type="submit">Get alerts</button>' + boxes
            + '<p class="al-say">' + SAY + '<a href="/alerts">All desks</a> &middot; <a href="/privacy#alerts">Privacy</a></p>'
            + '<p class="al-msg" role="status" aria-live="polite"></p></form>')


def desk_form(slug, name):
    return _form('<label class="al-c"><input type="checkbox" name="d" value="%s" checked> This desk (%s)</label>' % (E(slug), E(name)),
                 'Email me when this desk&rsquo;s outcome changes')


def brand_form(slug, name, desk_names):
    return _form('<label class="al-c"><input type="checkbox" name="o" value="%s" checked> This organisation (%s), on %s</label>' % (E(slug), E(name), E(_names(desk_names))),
                 'Email me when an outcome changes on a desk with rows about %s' % E(name))


def _insert(doc, frag):
    i = doc.rfind('</main>')
    return doc if i < 0 or 'class="al"' in doc else doc[:i] + frag + doc[i:]


def apply(PAGES, page, hero_slim, HOME, bb, rows):
    desks = alertable(PAGES); brands = brand_desks(bb, rows, desks)
    json.dump({'desks': desks, 'brands': brands}, open(MAP, 'w'), ensure_ascii=False, indent=0, sort_keys=True)
    js = ('// Generated by alerts.py at each build: the desks and organisations an outcome alert can follow. Do not edit by hand.\n'
          'export const ALERT_DESKS = %s;\nexport const ALERT_BRANDS = %s;\n' % (json.dumps(desks, ensure_ascii=False, sort_keys=True), json.dumps(brands, ensure_ascii=False, sort_keys=True)))
    if not os.path.exists(LIST_JS) or open(LIST_JS, encoding='utf-8').read() != js: open(LIST_JS, 'w', encoding='utf-8').write(js)
    for s, (nm, _) in desks.items(): PAGES['/' + s] = _insert(PAGES['/' + s], desk_form(s, nm))
    for s, (nm, ds) in brands.items():
        p = '/brand/' + s
        if p in PAGES: PAGES[p] = _insert(PAGES[p], brand_form(s, nm, [desks[d][0] for d in ds]))
    li = ''.join('<li><label><input type="checkbox" name="d" value="%s"> <strong>%s</strong> <span class="meta">%s</span></label> <a href="/%s">desk</a></li>'
                 % (E(s), E(nm), E(q), E(s)) for s, (nm, q) in sorted(desks.items(), key=lambda x: x[1][0]))
    body = ('<section class="legal"><p>Get one email when an outcome changes on a desk you follow. A change is what the desk&rsquo;s ledger rule counts as one: '
            'the outcome moves, for example from consistent to above, or a new value passes the rule the desk states. '
            'Moves inside the printed interval stay on the page and send nothing. Several changes found in one pass come in one email.</p>'
            '<p>We email a confirmation link first and send nothing else until you open it. Every alert has a link to manage your desks or unsubscribe. '
            'Each desk&rsquo;s changes are also on its own feed, for example <a href="/airq/changes.xml">/airq/changes.xml</a>, and each '
            '<a href="/brand">brand page</a> has a box for the desks with rows about that organisation.</p>'
            '<form class="al" action="/alerts/subscribe" method="post"><p class="al-h">Tick the desks you want</p><ul class="al-list">' + li + '</ul>'
            '<input type="email" name="email" required maxlength="160" autocomplete="email" placeholder="Email address" aria-label="Email address">'
            '<input class="nl-hp" type="text" name="website" tabindex="-1" autocomplete="off" aria-hidden="true">'
            '<button class="btn" type="submit">Get alerts</button><p class="al-say"><a href="/privacy#alerts">Privacy</a></p>'
            '<p class="al-msg" role="status" aria-live="polite"></p></form></section>')
    PAGES['/alerts'] = page('/alerts', 'Outcome Alerts | Heuremen LLC', 'One email when an outcome changes on the indahl.ai desks you follow, with a confirmation link first and a manage link in every alert.',
                            body, hero_slim('Outcome Alerts'))
    if HOME is not None: HOME['/alerts'] = '/hermes'
    tag = '<script src="/alerts.js?v=%s" defer></script>' % hashlib.sha256(JS_HASH_SRC.encode()).hexdigest()[:8]
    n = 0
    for k, d in PAGES.items():
        if 'class="al"' in d and '/alerts.js' not in d and '</body>' in d: PAGES[k] = d.replace('</body>', tag + '\n</body>', 1); n += 1
    print('alerts: sign-up box on %d desk pages and %d brand pages, /alerts built' % (len(desks), sum(1 for s in brands if '/brand/' + s in PAGES)))
    return desks, brands
