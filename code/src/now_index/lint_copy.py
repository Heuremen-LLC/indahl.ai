#!/usr/bin/env python3
"""lint_copy.py: house public-copy checks on the visible text of now.html written by us (quotes from sources are taken out first, since
they are the predictors' words, not ours). Prints every hit, exit 1 on any."""
import re, sys, html, os
H = os.path.dirname(os.path.abspath(__file__))
t = open(os.path.join(H, 'now.html')).read()
main = t.split('<main', 1)[1].split('</main>', 1)[0]
ours = re.sub(r'(?is)<span class="quote">.*?</span>', ' ', main)          # quoted words of others
ours = re.sub(r'(?is)<td><span class="quote">.*?</td>', ' ', ours)
ours = re.sub(r'(?is)<a [^>]*>.*?</a>', ' ', ours)                        # link text is a source's own title
vis = html.unescape(re.sub(r'<[^>]+>', ' ', re.sub(r'(?is)<script.*?</script>', ' ', ours)))
vis = re.sub(r'\s+', ' ', vis)
vis = re.sub(r"under the title '[^']*'", ' ', vis)   # a quoted title is the outlet's words
heads = [html.unescape(re.sub(r'<[^>]+>', '', h)) for h in re.findall(r'(?is)<h[1-3][^>]*>(.*?)</h[1-3]>', t)]
rules = [(r';', 'semicolon'), (r'\bby hand\b', '"by hand"'), (r'\bapparatus\b', 'apparatus'),
         (r'\b(Claude|assistant|written by an AI|generated by an AI)\b', 'AI statement'),   # AI and LLM as subject matter are allowed here
         (r'\b(stale|mistake|outdated|failed to|neglect|careless|sloppy|foolish|absurd|laughable|infamous|famously|notorious|hilarious|ridiculous|silly|naive|bold|wildly)\b', 'judgement word'),
         (r'\b(God|Christian\b|Islam|Jewish|Hindu|Buddhis|church|religio|prophet|biblical|Democrat|Republican|liberal|conservative|patriot)', 'religion or politics word'),
         (r'\bbecause\b', 'because (check no cause is named for a reading)'), (r'(?<!Artemis )(?<!Centurie )(?<!Jason )\bI\b(?! quatrain)|\bmy\b', 'first person singular'),
         (r'\bLLC\b(?<!Heuremen LLC)', 'LLC without Heuremen'), (r'\bIndahl\b', 'Indahl (the site says Heuremen LLC)')]
bad = 0
for pat, name in rules:
    for m in re.finditer(pat, vis):
        ctx = vis[max(0, m.start() - 90):m.end() + 90]
        print(f'{name}: ...{ctx}...'); bad += 1
for h in heads:
    if re.search(r'\d', h): print('count or digit in a heading:', h); bad += 1
if 'Wayfinder and Bones' not in vis: print('byline missing'); bad += 1
print('hits', bad)
sys.exit(1 if bad else 0)
