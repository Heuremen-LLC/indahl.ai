"""build.py: writes ~/.claude/commands/tp.md and q.md from the parts in this folder, so the two commands share one core and cannot drift.
tp = head_tp + core + packs Q, L, P, O + foot + the long-form reference (the old /tp body, kept whole). q = head_q + core + pack Q + pack P + foot."""
import os
H = os.path.dirname(os.path.abspath(__file__)); C = os.path.expanduser('~/.claude/commands')
def r(n): return open(os.path.join(H, n)).read().rstrip() + '\n'
SEP = '\n---\n\n'
gen = '<!-- GENERATED by ~/bones-forge/watch/checks/build.py from its parts. Edit the parts, then run build.py. -->\n'
tp = SEP.join([r('head_tp.md'), r('core.md'), '## PACK Q — quantum and QIA (the /q checklist, unchanged)\n\n' + r('pack_Q.md'), r('pack_L.md'), r('pack_P.md'), r('pack_O.md'), r('foot.md'),
                     '# REFERENCE — the long form of the shape questions, the catalogue and the internal reminders (the /tp body before the merge, kept whole)\n\n' + r('ref_tp_long.md') + '\n' + r('ref_tp_tail.md')])
q = SEP.join([r('head_q.md'), r('core.md'), '## PACK Q — quantum and QIA\n\n' + r('pack_Q.md'), r('pack_P.md'), r('foot.md')])
tp += '\n' + gen; q += '\n' + gen
open(os.path.join(C, 'tp.md'), 'w').write(tp); open(os.path.join(C, 'q.md'), 'w').write(q)
print('tp.md', len(tp.splitlines()), 'lines; q.md', len(q.splitlines()), 'lines')
